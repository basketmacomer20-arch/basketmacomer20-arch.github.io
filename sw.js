// Service worker: rende l'app disponibile offline.
// Quando modifichi index.html, aumenta VERSION per forzare l'aggiornamento sui dispositivi.
const VERSION = 'referto-v4';
const FILES = [
  './',
  './index.html',
  './manifest.webmanifest',
  './icons/icon-192.png',
  './icons/icon-512.png',
  './icons/icon-maskable-512.png',
  './icons/apple-touch-icon.png'
];

self.addEventListener('install', e => {
  e.waitUntil(caches.open(VERSION).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', e => {
  e.waitUntil(
    caches.keys()
      .then(keys => Promise.all(keys.filter(k => k !== VERSION).map(k => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Cache prima (apertura immediata anche con rete scarsa in palestra),
// aggiornamento in background: la versione nuova si vede alla riapertura successiva.
self.addEventListener('fetch', e => {
  if (e.request.method !== 'GET' || new URL(e.request.url).origin !== location.origin) return;
  e.respondWith(
    caches.open(VERSION).then(cache =>
      cache.match(e.request, { ignoreSearch: true }).then(cached => {
        const net = fetch(e.request)
          .then(res => { if (res.ok) cache.put(e.request, res.clone()); return res; })
          .catch(() => cached || cache.match('./index.html'));
        if (cached) { e.waitUntil(net.catch(() => {})); return cached; }
        return net;
      })
    )
  );
});
